ICONS: dict = {}
DEFAULT_ICON_UNICODE: dict = {}
ICON_CATEGORIES: dict = {}

for _name, _category, _cp, _variant in _ICON_ROWS:
    _glyph = chr(_cp) + (_VS16 if _variant else "")
    ICONS[_name] = {
        "name": _name,
        "category": _category,
        "glyph": _glyph,
        "codepoint": f"U+{_cp:04X}",
        "vector": None,
        "document_id": None,
    }
    DEFAULT_ICON_UNICODE[_name] = _glyph
    ICON_CATEGORIES.setdefault(_category, []).append(_name)

del _name, _category, _cp, _variant, _glyph


def document_id_for(name: str):
    real = ICON_DOCUMENT_IDS.get(name)
    if real:
        return real
    entry = ICONS.get(name)
    return entry["document_id"] if entry else None


class IconKit:
    """The icon catalog lookup.

    One instance (``icon_kit``); the module-level function below is a
    backward-compatible alias.
    """

    document_id_for = staticmethod(document_id_for)


icon_kit = IconKit()


